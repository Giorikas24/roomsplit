import { z } from "zod";

export const expenseSchema = z.object({
  description: z.string().trim().min(1, "Η περιγραφή είναι υποχρεωτική").max(120),

  // Δεχόμαστε λεπτά, όχι ευρώ. Ο λόγος είναι ότι το 19.99
  // δεν αποθηκεύεται ακριβώς σε δεκαδικό αριθμό υπολογιστή
  // και μετά από αρκετές πράξεις εμφανίζονται σφάλματα.
  amountCents: z.int().positive("Το ποσό πρέπει να είναι θετικό"),

  // Μορφή ΕΕΕΕ-ΜΜ-ΗΗ, χωρίς ώρα.
  date: z.iso.date(),

  // Αν λείπει, θεωρούμε ότι πλήρωσε αυτός που καταχωρεί.
  paidById: z.string().optional(),

  // Δεν συμμετέχουν πάντα όλοι, π.χ. πίτσα που πήραν
  // οι τρεις από τους τέσσερις.
  participantIds: z.array(z.string()).min(1, "Χρειάζεται τουλάχιστον ένας συμμετέχων"),
});
